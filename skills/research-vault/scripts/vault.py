class VaultError(RuntimeError):
    """Base error for a Research Vault boundary violation."""


class ContainmentError(VaultError):
    """A path is outside the vault or follows an unsafe link."""


class ReservedPathError(VaultError):
    """A v1, product-owned, or unknown hidden path was targeted."""


class OwnershipError(VaultError):
    """A user-owned path was targeted by a vault mutation."""


class CASConflict(VaultError):
    """A target changed since the caller read its expected digest."""


class JournalError(VaultError):
    """An operation journal is incomplete, corrupt, or not recoverable."""


